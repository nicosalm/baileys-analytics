async function quickGenerateReport(
  request: HttpRequest,
  context: InvocationContext
): Promise<HttpResponseInit> {
  const authResult = await requireAuth(request)
  if (!authResult.authenticated) {
    return authResult.response
  }
  const { auth } = authResult.request

  const tenantError = requireTenant(auth.tenantId)
  if (tenantError) return tenantError

  try {
    const body = await request.json() as QuickReportConfig
    
    // Calculate date range
    const dateRange = calculateDateRange(body.dateRange)
    
    // Fetch report data based on modules
    const reportData = await fetchReportData(
      body.modules,
      dateRange,
      auth.tenantId!,
      {
        tags: body.tags,
        properties: body.properties
      }
    )
    
    // Generate PDF
    const pdfBuffer = await generateQuickPDF(
      'Quick Report',
      body,
      reportData,
      auth.tenantId!
    )
    
    // Return PDF directly
    return {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="Quick-Report-${formatDateISO(new Date())}.pdf"`,
        'Cache-Control': 'no-cache',
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type, Authorization'
      },
      body: pdfBuffer
    }
  } catch (error) {
    context.error('Error generating quick report:', error)
    return createErrorResponse('Failed to generate report')
  }
}

app.http('reports-quick-generate', {
  methods: ['POST', 'OPTIONS'],
  authLevel: 'anonymous',
  route: 'reports/quick-generate',
  handler: quickGenerateReport
})